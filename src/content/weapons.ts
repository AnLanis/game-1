function aiVariant(id: string, base: string, overrides: Partial<WeaponDef>): WeaponDef {
  // Resolved lazily below once WEAPONS exists; placeholder carries base id.
  return { id, aiOnly: true, __base: base, ...overrides } as unknown as WeaponDef;
}

// Resolve AI variants against their base definitions.
for (let i = 0; i < WEAPONS.length; i += 1) {
  const w = WEAPONS[i] as WeaponDef & { __base?: string };
  if (!w.__base) continue;
  const base = WEAPONS.find((b) => b.id === w.__base);
  if (!base) throw new Error(`AI weapon base ${w.__base} missing`);
  const { __base, ...overrides } = w;
  void __base;
  WEAPONS[i] = {
    ...base,
    ...overrides,
    name: `${base.name} (AI)`,
    unlockLevel: 999,
    reserve: 9999,
    aiOnly: true,
  } as WeaponDef;
}

